"""口径字典：把「指标别名」和「同名不同口径」分开管。

为什么需要这一层
----------------
老师点名要修的三类错，有一类叫「指标别名」。但别名其实是两种东西：

  ① **同一口径的不同写法**（可以互换）
     归属于上市公司股东的净利润 = 归属于母公司所有者的净利润 = 归母净利润
     这是「别名」。回答时写哪个都对，指的是同一行数字。

  ② **名字很像、口径完全不同**（不能互换）
     归母净利润 ≠ 扣非归母净利润 ≠ 净利润（含少数股东）
     基本每股收益 ≠ 稀释每股收益
     营业成本 ≠ 营业总成本
     资产总计 ≠ 归属于母公司所有者权益合计
     这不是别名，是**同名的坑**。把 ② 当成 ① 处理，答案就会「数对、口径错」——
     比答错更危险，因为看起来是对的。

所以字典里每个指标都写两组词：
  same      同一口径的写法（问句命中任意一个，都指向这一行）
  distinct  长得像但口径不同的行（回答时用了这些行 = 口径错，必须报出来）

配套：
  查口径.py   用这份字典做「单位 / 负号 / 口径」三项核对与修复
  指标规则.py 仍按原来的 5 组通用表头规则做排序加权，本文件不改它的权重

只放「说法 → 标准科目 / 口径」的映射与单位约定，**不含任何公司名、年份、数值**。
"""

