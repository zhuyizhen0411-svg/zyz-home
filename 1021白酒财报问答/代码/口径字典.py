def _prefer_by_metric(query):
    """「扣非」是修饰语，不是指标名：得先看它修饰的是谁。

    「扣除非经常性损益后的加权平均净资产收益率」问的是 ROE，
    「扣非归母净利润」问的是净利润 —— 两者只差一个词，靠 DETECT_ORDER 的先后
    会把 ROE/EPS 题判成净利润题（我在题库3上就踩到了）。
    所以这里先认指标本身，再让「扣非」只决定取哪一行。
    """
    is_kf = ("扣非" in query) or ("扣除非经常性损益" in query)
    if ("每股收益" in query) or ("每股盈利" in query) or ("EPS" in query) or ("eps" in query):
        return "稀释每股收益" if ("稀释" in query or "摊薄" in query) else "基本每股收益"
    if ("净资产收益率" in query) or ("ROE" in query) or ("roe" in query):
        return "扣非加权平均净资产收益率" if is_kf else "加权平均净资产收益率"
    return None


def detect(query, strict_alias=True):
    """识别问句问的是哪个口径。

    返回 (key 或 None, 命中的说法)。
    规则：先认指标本身（ROE / 每股收益优先于「扣非」这个修饰语），
    再按 DETECT_ORDER 的顺序找；命中更具体口径后，把它同族里较宽的口径剔掉。
    """
    if not query:
        return None, None
    pref = _prefer_by_metric(query)
    if pref and pref in CALIBERS:
        return pref, next((a for a in CALIBERS[pref]["aliases"] if a in query), pref)
    hits = []
    for key in DETECT_ORDER:
        for alias in CALIBERS[key]["aliases"]:
            if alias in query:
                hits.append((key, alias))
                break
    if not hits:
        return None, None
    keys = [k for k, _ in hits]
    out = []
    for k, a in hits:
        blocked = set()
        for other in out:
            blocked.update(EXCLUSIVE_GROUP.get(other, ()))
        if k in blocked:
            continue
        out.append(k)
    if not out:
        return hits[0]
    # 命中多个不互斥的口径时，取字典顺序靠前的（更具体）
    key = out[0]
    alias = next(a for k, a in hits if k == key)
    return key, alias


def same_terms(key):
    return list(CALIBERS[key]["same"]) if key in CALIBERS else []


def distinct_terms(key):
    return list(CALIBERS[key]["distinct"]) if key in CALIBERS else []


_ROW_CACHE = {}


def row_pattern(key):
    """「该口径所在行」的正则：命中 same 里的任意写法。"""
    if key not in _ROW_CACHE:
        terms = same_terms(key)
        _ROW_CACHE[key] = re.compile("|".join(re.escape(t) for t in terms)) if terms else None
    return _ROW_CACHE[key]


_DISTINCT_CACHE = {}


def distinct_pattern(key):
    """「长得像但口径不对的行」的正则。"""
    if key not in _DISTINCT_CACHE:
        terms = distinct_terms(key)
        _DISTINCT_CACHE[key] = re.compile("|".join(re.escape(t) for t in terms)) if terms else None
    return _DISTINCT_CACHE[key]


