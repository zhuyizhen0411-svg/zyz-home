_COMPILED = tuple((re.compile(p), name) for p, name in COLLOQUIAL_RULES)

# 判断是否「真的取到了目标科目」：科目名 + 至少一个千分位金额
_FIG_RE = re.compile(r"\d{1,3}(?:,\d{3}){2,}")


def expand(query):
    """返回问句对应的标准科目名列表（去重、保持规则顺序）。"""
    if not query:
        return []
    out = []
    for rx, name in _COMPILED:
        if rx.search(query) and name not in out:
            out.append(name)
    return out


def synonyms(names):
    """把标准科目名展开成常见写法集合（含原名的近义词族）。"""
    terms = []
    for n in names:
        for t in (n,) + SUBJECT_SYNONYMS.get(n, ()):
            if t not in terms:
                terms.append(t)
    return terms


def rewrite(query):
    """把问句改写成「原句 + 标准科目名 + 同族近义词」，供额外一路 BM25 使用。

    没识别出任何口语说法时返回 None（保持原有检索路径不变）。
    """
    names = expand(query)
    if not names:
        return None
    return query + " " + " ".join(synonyms(names))


def terms_of(query):
    """问句的目标词：识别出的科目名 + 同族近义词；没识别到就回退为问句实义词。"""
    names = expand(query)
    if names:
        return synonyms(names)
    return _content_words(query)


def hit_terms(text, terms):
    """块里是否出现了任一目标词（用于判断这家公司有没有取到目标科目）。"""
    if not terms or not text:
        return False
    return any(t in text for t in terms)


def has_target_row(text, terms):
    """更严格：块里同时出现目标词和千分位金额——即真的取到了那个科目的数字。"""
    return hit_terms(text, terms) and bool(_FIG_RE.search(text))


_STOP = ("多少", "分别", "各自", "哪些", "哪家", "谁的", "怎么", "是否", "还是", "比较", "排名",
         "排序", "前三", "请问", "帮我", "查一下", "公司", "上市", "白酒", "企业", "各家", "每家",
         "这家", "情况", "如何", "怎样", "金额", "数值")


def _content_words(query):
    """没识别出科目时，退回取问句里的实义词（去公司名/年份/虚词后的中文词）。"""
    try:
        from 词频检索 import get_tokenize

        toks = [t for t in get_tokenize()(query) if any("\u4e00" <= c <= "\u9fff" for c in t)]
    except Exception:  # noqa: BLE001
        toks = re.findall(r"[\u4e00-\u9fff]{2,6}", query)
    out = []
    for t in toks:
        if len(t) < 2 or t in _STOP:
            continue
        if re.fullmatch(r"20\d{2}年?", t):
            continue
        if t not in out:
            out.append(t)
    return out[:8]


